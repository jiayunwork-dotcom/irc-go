package ircevent

// SCRAM-SHA-256 (RFC 5802 as profiled by RFC 7677) SASL client support.
// The exchange is driven entirely by AUTHENTICATE callbacks on the read
// goroutine, so no additional locking is required. Per-connection state
// is reset in connectInternal(), meaning that an automatic reconnect
// restarts the exchange from client-first with a fresh nonce.

import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"errors"
	"fmt"
	"strconv"
	"strings"
	"time"

	"github.com/ergochat/irc-go/ircmsg"
	"github.com/ergochat/irc-go/ircutils"
)

const (
	scramMech = "SCRAM-SHA-256"

	// scramNonceLen is the size in bytes of the random client nonce
	// before base64 encoding.
	scramNonceLen = 24

	// upper bound on an advertised iteration count, used to keep a
	// malicious server from forcing expensive key derivation
	scramMaxIterations = 1000000

	// maximum amount of server AUTHENTICATE data buffered for one message
	scramMaxBufferSize = 64 * 1024

	// GS2 header for no channel binding and no authorization identity:
	scramGS2Header = "n,,"
)

// scramPhase tracks progress through the four-message SCRAM exchange.
type scramPhase int

const (
	// client-first has been sent, waiting for server-first
	scramClientFirstSent scramPhase = iota
	// client-final has been sent, waiting for server-final
	scramClientFinalSent
	// the server signature was verified, the empty response was sent
	scramVerified
)

// scramSession is the pure SCRAM-SHA-256 protocol state machine.
type scramSession struct {
	phase    scramPhase
	login    string
	password string

	clientNonce     string // nonce generated by the client
	nonce           string // full nonce (client nonce + server nonce)
	clientFirstBare string // client-first-message-bare
	serverFirst     string // exact server-first-message received
	authMessage     string // AuthMessage input to the signature HMACs
	serverKey       []byte // ServerKey derived from the password
}

// scramExchange bundles the protocol state machine with the IRCv3
// chunk reassembly buffer for incoming AUTHENTICATE parameters.
type scramExchange struct {
	session *scramSession
	buffer  *ircutils.SASLBuffer
}

type scramAttribute struct {
	key   byte
	value string
}

// generateSCRAMNonce returns a fresh random nonce made up of printable
// ASCII characters that never contains a comma or '='.
func generateSCRAMNonce() (string, error) {
	buf := make([]byte, scramNonceLen)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

// escapeSCRAMUsername applies the RFC 5802 username quoting:
// '=' becomes '=3D' and ',' becomes '=2C'.
func escapeSCRAMUsername(username string) string {
	return strings.NewReplacer("=", "=3D", ",", "=2C").Replace(username)
}

// newSCRAMSession generates a new nonce and prepares the client-first
// message, which is sent immediately after the exchange starts.
func newSCRAMSession(login, password string) (*scramSession, error) {
	clientNonce, err := generateSCRAMNonce()
	if err != nil {
		return nil, err
	}
	session := &scramSession{
		phase:       scramClientFirstSent,
		login:       login,
		password:    password,
		clientNonce: clientNonce,
	}
	session.clientFirstBare = fmt.Sprintf("n=%s,r=%s",
		escapeSCRAMUsername(login), clientNonce)
	return session, nil
}

// clientFirstMessage returns the full GS2-wrapped client-first message.
func (s *scramSession) clientFirstMessage() []byte {
	return []byte(scramGS2Header + s.clientFirstBare)
}

// parseSCRAMAttributes splits a message into its comma-separated
// key=value attributes, rejecting malformed entries, duplicate attribute
// names and the reserved mandatory-extension attribute 'm'.
func parseSCRAMAttributes(message string) (attrs []scramAttribute, err error) {
	seen := make(map[byte]bool)
	for _, pair := range strings.Split(message, ",") {
		// every attribute is a single-letter key, '=' and a value
		if len(pair) < 3 || pair[1] != '=' {
			return nil, errors.New("scram: malformed attribute in server message")
		}
		key := pair[0]
		if key == 'm' {
			return nil, errors.New("scram: server advertised an unsupported mandatory extension")
		}
		if seen[key] {
			return nil, fmt.Errorf("scram: duplicate attribute %q in server message", string(key))
		}
		seen[key] = true
		attrs = append(attrs, scramAttribute{key: key, value: pair[2:]})
	}
	return attrs, nil
}

func scramAttributeValue(attrs []scramAttribute, key byte) (value string, ok bool) {
	for _, attr := range attrs {
		if attr.key == key {
			return attr.value, true
		}
	}
	return "", false
}

// handleServerFirst validates the server-first message and produces the
// client-final message.
func (s *scramSession) handleServerFirst(raw []byte) (clientFinal []byte, err error) {
	if s.phase != scramClientFirstSent {
		return nil, errors.New("scram: received server-first message in the wrong exchange state")
	}

	serverFirst := string(raw)
	attrs, err := parseSCRAMAttributes(serverFirst)
	if err != nil {
		return nil, err
	}

	nonce, ok := scramAttributeValue(attrs, 'r')
	if !ok {
		return nil, errors.New("scram: server-first message is missing the nonce")
	}
	saltEncoded, ok := scramAttributeValue(attrs, 's')
	if !ok {
		return nil, errors.New("scram: server-first message is missing the salt")
	}
	iterationEncoded, ok := scramAttributeValue(attrs, 'i')
	if !ok {
		return nil, errors.New("scram: server-first message is missing the iteration count")
	}

	// the combined nonce must preserve the client nonce and append a
	// non-empty server-generated part
	if !strings.HasPrefix(nonce, s.clientNonce) || len(nonce) == len(s.clientNonce) {
		return nil, errors.New("scram: server nonce does not extend the client nonce")
	}

	salt, err := base64.StdEncoding.DecodeString(saltEncoded)
	if err != nil {
		return nil, errors.New("scram: server-first message contains an invalid salt")
	}

	iterations, err := strconv.Atoi(iterationEncoded)
	if err != nil || iterations <= 0 || iterations > scramMaxIterations {
		return nil, errors.New("scram: server-first message contains an invalid iteration count")
	}

	saltedPassword := pbkdf2SHA256([]byte(s.password), salt, iterations, sha256.Size)
	clientKey := hmacSHA256(saltedPassword, "Client Key")
	storedKey := sha256Sum(clientKey)

	channelBinding := base64.StdEncoding.EncodeToString([]byte(scramGS2Header))
	clientFinalWithoutProof := fmt.Sprintf("c=%s,r=%s", channelBinding, nonce)
	authMessage := strings.Join([]string{s.clientFirstBare, serverFirst, clientFinalWithoutProof}, ",")

	clientSignature := hmacSHA256(storedKey, authMessage)
	proof := xorBytes(clientKey, clientSignature)

	// retain everything needed to verify the server-final message
	s.nonce = nonce
	s.serverFirst = serverFirst
	s.authMessage = authMessage
	s.serverKey = hmacSHA256(saltedPassword, "Server Key")
	s.phase = scramClientFinalSent

	return []byte(clientFinalWithoutProof + ",p=" + base64.StdEncoding.EncodeToString(proof)), nil
}

// handleServerFinal validates the server-final message, in particular the
// server signature proving the server knows the password-derived keys.
func (s *scramSession) handleServerFinal(raw []byte) error {
	if s.phase != scramClientFinalSent {
		return errors.New("scram: received server-final message in the wrong exchange state")
	}

	attrs, err := parseSCRAMAttributes(string(raw))
	if err != nil {
		return err
	}

	if serverError, ok := scramAttributeValue(attrs, 'e'); ok && serverError != "" {
		return errors.New("scram: server reported an authentication error")
	}

	signatureEncoded, ok := scramAttributeValue(attrs, 'v')
	if !ok {
		return errors.New("scram: server-final message is missing the server signature")
	}
	signature, err := base64.StdEncoding.DecodeString(signatureEncoded)
	if err != nil {
		return errors.New("scram: server-final message contains an invalid server signature")
	}

	expectedSignature := hmacSHA256(s.serverKey, s.authMessage)
	if !hmac.Equal(signature, expectedSignature) {
		return errors.New("scram: server signature verification failed")
	}

	s.phase = scramVerified
	return nil
}

// scramHandleAuthenticate drives the SCRAM exchange from AUTHENTICATE
// callbacks. All errors abort the exchange with AUTHENTICATE * and are
// reported through the existing saslChan mechanism; error text never
// includes the password.
func (irc *Connection) scramHandleAuthenticate(e ircmsg.Message) {
	if len(e.Params) == 0 {
		return
	}
	payload := e.Params[0]

	// explicit server-side abort, valid at any point of the exchange
	if payload == "*" {
		irc.scram = nil
		irc.submitSASLResult(saslResult{Failed: true, Err: errors.New("scram: authentication exchange aborted by server")})
		return
	}

	// the server starts the exchange with an empty challenge
	if irc.scram == nil {
		if payload != "+" {
			irc.failSCRAM(errors.New("scram: expected an empty authentication challenge to start the exchange"))
			return
		}
		session, err := newSCRAMSession(irc.SASLLogin, irc.SASLPassword)
		if err != nil {
			irc.failSCRAM(fmt.Errorf("scram: could not initialize the exchange: %w", err))
			return
		}
		irc.scram = &scramExchange{
			session: session,
			buffer:  ircutils.NewSASLBuffer(scramMaxBufferSize),
		}
		irc.sendSCRAMMessage(session.clientFirstMessage())
		return
	}

	done, raw, err := irc.scram.buffer.Add(payload)
	if err != nil {
		irc.failSCRAM(fmt.Errorf("scram: could not decode authentication data: %w", err))
		return
	}
	if !done {
		// waiting for more 400-byte chunks
		return
	}

	switch irc.scram.session.phase {
	case scramClientFirstSent:
		clientFinal, err := irc.scram.session.handleServerFirst(raw)
		if err != nil {
			irc.failSCRAM(err)
			return
		}
		irc.sendSCRAMMessage(clientFinal)
	case scramClientFinalSent:
		if err := irc.scram.session.handleServerFinal(raw); err != nil {
			irc.failSCRAM(err)
			return
		}
		// signature verified: send the empty response and wait for
		// 903 RPL_SASLSUCCESS before performHandshake() sends CAP END
		irc.Send("AUTHENTICATE", "+")
	default:
		irc.failSCRAM(errors.New("scram: received an unexpected authentication message after the exchange completed"))
	}
}

// sendSCRAMMessage emits a raw SCRAM message as IRCv3 AUTHENTICATE
// parameters, splitting the base64 payload into chunks of at most
// 400 bytes and appending a terminating '+' when the final chunk is
// exactly 400 bytes.
func (irc *Connection) sendSCRAMMessage(raw []byte) {
	for _, chunk := range ircutils.EncodeSASLResponse(raw) {
		irc.Send("AUTHENTICATE", chunk)
	}
}

// failSCRAM aborts the current exchange, tells the server via
// AUTHENTICATE * and reports the failure through the standard SASL
// result channel. The performHandshake() fallback (including
// SASLOptional) then applies unchanged.
//
// The abort frame is written synchronously before the SASL result is
// published: performHandshake() may tear the connection down as soon
// as it receives the result, so a normal queued Send() would race the
// socket close and could never reach the server.
func (irc *Connection) failSCRAM(err error) {
	irc.scram = nil
	irc.writeSCRAMAbort()
	irc.submitSASLResult(saslResult{Failed: true, Err: err})
}

// writeSCRAMAbort writes the AUTHENTICATE * abort frame directly to the
// socket, serialized with the writeLoop through writeMutex.
func (irc *Connection) writeSCRAMAbort() {
	irc.writeMutex.Lock()
	defer irc.writeMutex.Unlock()
	if irc.socket == nil {
		return
	}
	irc.socket.SetWriteDeadline(time.Now().Add(irc.Timeout))
	_, writeErr := irc.socket.Write([]byte("AUTHENTICATE *\r\n"))
	irc.socket.SetWriteDeadline(time.Time{})
	if writeErr != nil {
		irc.setError(writeErr)
	}
}

func hmacSHA256(key []byte, message string) []byte {
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(message))
	return mac.Sum(nil)
}

func sha256Sum(data []byte) []byte {
	sum := sha256.Sum256(data)
	return sum[:]
}

func xorBytes(a, b []byte) []byte {
	result := make([]byte, len(a))
	for i := range a {
		result[i] = a[i] ^ b[i]
	}
	return result
}

// pbkdf2SHA256 derives a key using PBKDF2 with HMAC-SHA-256 as the
// pseudorandom function (RFC 2898 / RFC 5802 section 2.2).
func pbkdf2SHA256(password, salt []byte, iterations, keyLength int) []byte {
	hashLength := sha256.Size
	numBlocks := (keyLength + hashLength - 1) / hashLength
	result := make([]byte, 0, numBlocks*hashLength)

	var blockIndex [4]byte
	for block := 1; block <= numBlocks; block++ {
		binary.BigEndian.PutUint32(blockIndex[:], uint32(block))

		mac := hmac.New(sha256.New, password)
		mac.Write(salt)
		mac.Write(blockIndex[:])
		u := mac.Sum(nil)

		derived := make([]byte, hashLength)
		copy(derived, u)
		for iteration := 1; iteration < iterations; iteration++ {
			mac = hmac.New(sha256.New, password)
			mac.Write(u)
			u = mac.Sum(nil)
			for i := range derived {
				derived[i] ^= u[i]
			}
		}
		result = append(result, derived...)
	}

	return result[:keyLength]
}
